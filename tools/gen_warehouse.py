#!/usr/bin/env python3
"""Generate the NOVA warehouse Gazebo world AND its matching Nav2 map from ONE layout.

Edit LAYOUT below, then run from the workspace root:
    python3 tools/gen_warehouse.py
Writes:
    src/nova_gazebo/worlds/warehouse.sdf
    src/nova_navigation/maps/warehouse.pgm + warehouse.yaml
Station coordinates used by the mission manager live in
    src/nova_mission/config/stations.yaml   (keep them in the free aisles below)
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Inner floor area is x in [-HALF_X, HALF_X], y in [-HALF_Y, HALF_Y]
HALF_X, HALF_Y = 6.0, 4.0
WALL_T, WALL_H = 0.2, 1.0

# (name, cx, cy, sx, sy, sz, rgba)
BOXES = [
    ('shelf_a', -2.0,  1.5, 3.0, 0.6, 1.2, '0.95 0.55 0.10 1'),
    ('shelf_b', -2.0, -1.5, 3.0, 0.6, 1.2, '0.95 0.55 0.10 1'),
    ('shelf_c',  2.5,  1.5, 3.0, 0.6, 1.2, '0.15 0.45 0.85 1'),
    ('shelf_d',  2.5, -1.5, 3.0, 0.6, 1.2, '0.15 0.45 0.85 1'),
    ('crate_1', -4.5,  3.0, 0.8, 0.8, 0.6, '0.55 0.40 0.25 1'),
    ('crate_2', -4.5, -3.0, 0.8, 0.8, 0.6, '0.55 0.40 0.25 1'),
]
# (name, cx, cy, radius, height)
PILLARS = [
    ('pillar_n', 0.25,  2.8, 0.15, 1.5),
    ('pillar_s', 0.25, -2.8, 0.15, 1.5),
]
# floor markers (visual only) -> must match nova_mission/config/stations.yaml
STATIONS = [
    ('home',   -5.0,  0.0, '0.2 0.8 0.2 1'),
    ('pick_a', -2.0,  0.6, '0.95 0.8 0.1 1'),
    ('pick_b', -2.0, -0.6, '0.95 0.8 0.1 1'),
    ('pick_c',  2.5,  2.6, '0.95 0.8 0.1 1'),
    ('pick_d',  2.5, -2.6, '0.95 0.8 0.1 1'),
    ('drop_1',  5.0,  2.0, '0.9 0.2 0.2 1'),
    ('drop_2',  5.0, -2.0, '0.9 0.2 0.2 1'),
]

MAP_RES = 0.05
MAP_MARGIN = 0.5


def walls():
    lx, ly = 2 * HALF_X + 2 * WALL_T, 2 * HALF_Y + 2 * WALL_T
    return [
        ('wall_n', 0.0, HALF_Y + WALL_T / 2, lx, WALL_T, WALL_H, '0.7 0.7 0.72 1'),
        ('wall_s', 0.0, -HALF_Y - WALL_T / 2, lx, WALL_T, WALL_H, '0.7 0.7 0.72 1'),
        ('wall_e', HALF_X + WALL_T / 2, 0.0, WALL_T, ly, WALL_H, '0.7 0.7 0.72 1'),
        ('wall_w', -HALF_X - WALL_T / 2, 0.0, WALL_T, ly, WALL_H, '0.7 0.7 0.72 1'),
    ]


def material(rgba):
    return (f'<material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse>'
            f'<specular>0.1 0.1 0.1 1</specular></material>')


def box_model(name, cx, cy, sx, sy, sz, rgba):
    geom = f'<geometry><box><size>{sx} {sy} {sz}</size></box></geometry>'
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {sz / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision">{geom}</collision>
        <visual name="visual">{geom}{material(rgba)}</visual>
      </link>
    </model>"""


def pillar_model(name, cx, cy, r, h):
    geom = f'<geometry><cylinder><radius>{r}</radius><length>{h}</length></cylinder></geometry>'
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {h / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision">{geom}</collision>
        <visual name="visual">{geom}{material('0.5 0.5 0.5 1')}</visual>
      </link>
    </model>"""


def station_markers():
    visuals = []
    for name, x, y, rgba in STATIONS:
        visuals.append(f"""
        <visual name="{name}">
          <pose>{x} {y} 0.002 0 0 0</pose>
          <geometry><box><size>0.5 0.5 0.004</size></box></geometry>
          {material(rgba)}
        </visual>""")
    return f"""
    <model name="station_markers">
      <static>true</static>
      <link name="link">{''.join(visuals)}
      </link>
    </model>"""


def world_sdf():
    models = ''.join(box_model(*b) for b in walls() + BOXES)
    models += ''.join(pillar_model(*p) for p in PILLARS)
    models += station_markers()
    return f"""<?xml version="1.0"?>
<!-- GENERATED by tools/gen_warehouse.py — edit the layout there, not here. -->
<sdf version="1.9">
  <world name="nova_warehouse">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.78 0.82 0.88 1</background>
      <shadows>true</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          {material('0.45 0.45 0.47 1')}
        </visual>
      </link>
    </model>
{models}
  </world>
</sdf>
"""


def write_map():
    xmin, xmax = -HALF_X - MAP_MARGIN, HALF_X + MAP_MARGIN
    ymin, ymax = -HALF_Y - MAP_MARGIN, HALF_Y + MAP_MARGIN
    w = int(round((xmax - xmin) / MAP_RES))
    h = int(round((ymax - ymin) / MAP_RES))
    FREE, OCC, UNK = 254, 0, 205
    grid = [[UNK] * w for _ in range(h)]

    def cell_center(i, j):           # i = column, j = row from bottom
        return xmin + (i + 0.5) * MAP_RES, ymin + (j + 0.5) * MAP_RES

    rects = [(cx, cy, sx, sy) for _, cx, cy, sx, sy, _, _ in walls() + BOXES]
    for j in range(h):
        for i in range(w):
            x, y = cell_center(i, j)
            inside = abs(x) <= HALF_X and abs(y) <= HALF_Y
            val = FREE if inside else UNK
            for cx, cy, sx, sy in rects:
                if abs(x - cx) <= sx / 2 and abs(y - cy) <= sy / 2:
                    val = OCC
                    break
            else:
                for _, px, py, r, _ in PILLARS:
                    if math.hypot(x - px, y - py) <= r:
                        val = OCC
                        break
            grid[h - 1 - j][i] = val  # PGM row 0 = top (max y)

    maps_dir = os.path.join(ROOT, 'src', 'nova_navigation', 'maps')
    os.makedirs(maps_dir, exist_ok=True)
    with open(os.path.join(maps_dir, 'warehouse.pgm'), 'wb') as f:
        f.write(f'P5\n# NOVA warehouse (generated)\n{w} {h}\n255\n'.encode())
        f.write(bytes(v for row in grid for v in row))
    with open(os.path.join(maps_dir, 'warehouse.yaml'), 'w') as f:
        f.write('image: warehouse.pgm\n'
                'mode: trinary\n'
                f'resolution: {MAP_RES}\n'
                f'origin: [{xmin}, {ymin}, 0.0]\n'
                'negate: 0\n'
                'occupied_thresh: 0.65\n'
                'free_thresh: 0.25\n')
    print(f'wrote maps/warehouse.pgm ({w}x{h}) + warehouse.yaml')


if __name__ == '__main__':
    worlds_dir = os.path.join(ROOT, 'src', 'nova_gazebo', 'worlds')
    os.makedirs(worlds_dir, exist_ok=True)
    with open(os.path.join(worlds_dir, 'warehouse.sdf'), 'w') as f:
        f.write(world_sdf())
    print('wrote worlds/warehouse.sdf')
    write_map()
